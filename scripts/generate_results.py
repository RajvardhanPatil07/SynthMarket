"""Generate reproducible real-vs-synthetic evidence for docs/RESULTS.md and
docs/BENCHMARK_RESULTS.md.

This script is a scaffold, not a black box: it is written against the public class names
that exist in this package as of v0.2 (SyntheticMarketGenerator, StylizedFactsEvaluator,
run_benchmark, write_backtrader_csv_bundle, write_vectorbt_close_matrix_csv). Constructor
arguments can drift between versions, so read the docstrings/signatures in your local
checkout and adjust the marked TODO sections before trusting the output. Do not hand-edit
the generated markdown afterwards -- rerun the script instead, so the numbers stay honest.

Usage:
    python scripts/generate_results.py --ticker SPY --checkpoint artifacts/wgan_v2.pt \\
        --start 2015-01-01 --end 2024-12-31 --num-paths 20

Requires (not bundled with this repo's base install unless already present):
    torch, yfinance, backtrader, vectorbt
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ticker", required=True, help="Ticker symbol for real data, e.g. SPY")
    parser.add_argument("--checkpoint", required=True, help="Path to a trained WGAN checkpoint")
    parser.add_argument("--start", default="2015-01-01")
    parser.add_argument("--end", default="2024-12-31")
    parser.add_argument("--num-paths", type=int, default=20)
    parser.add_argument("--out-dir", default="docs")
    parser.add_argument("--benchmark", action="store_true", help="Also run the strategy benchmark")
    return parser.parse_args()


def load_real_data(ticker: str, start: str, end: str) -> pd.DataFrame:
    # TODO: replace with synthmarket.data_utils.prepare_market_data(MarketDataConfig(...))
    # if that helper already handles caching/column naming the way you want.
    import yfinance as yf

    df = yf.download(ticker, start=start, end=end, progress=False)
    df = df.rename(columns=str.lower)
    return df[["open", "high", "low", "close", "volume"]].dropna()


def generate_synthetic_paths(checkpoint: str, num_paths: int, length: int) -> list[pd.DataFrame]:
    # TODO: confirm the exact constructor/generate() signature in synthmarket/generator.py
    # for your installed version and adjust accordingly.
    from synthmarket.generator import SyntheticMarketGenerator

    generator = SyntheticMarketGenerator(checkpoint_path=checkpoint)
    paths = [generator.generate(length=length) for _ in range(num_paths)]
    return paths


def stylized_facts_report(real: pd.DataFrame, synthetic_paths: list[pd.DataFrame]) -> dict:
    from synthmarket.evaluator import StylizedFactsEvaluator

    evaluator = StylizedFactsEvaluator()
    reports = [evaluator.evaluate(real, synth) for synth in synthetic_paths]  # TODO: verify method name
    return {"per_path": [r.to_dict() if hasattr(r, "to_dict") else r for r in reports]}


def run_strategy_benchmark(real: pd.DataFrame, synthetic_paths: list[pd.DataFrame]) -> dict:
    from synthmarket.benchmark import run_benchmark  # TODO: verify signature against installed version
    from synthmarket import strategies as strat_module

    strategy_names = [name for name in dir(strat_module) if name[0].isupper()]
    # TODO: run_benchmark expects (model_names, evaluator_callable, ...) per the source --
    # wire this up to actually score each strategy on real vs synthetic paths once you've
    # confirmed the call signature locally.
    return {"strategies_considered": strategy_names}


def render_results_markdown(stylized: dict, out_path: Path) -> None:
    out_path.write_text(
        "# Stylized-Facts Results: Real vs. Synthetic\n\n"
        "_Auto-generated by scripts/generate_results.py -- do not hand edit._\n\n"
        f"```json\n{json.dumps(stylized, indent=2, default=str)}\n```\n"
    )


def render_benchmark_markdown(benchmark: dict, out_path: Path) -> None:
    out_path.write_text(
        "# Strategy Benchmark: Real vs. Synthetic Market Data\n\n"
        "_Auto-generated by scripts/generate_results.py -- do not hand edit._\n\n"
        f"```json\n{json.dumps(benchmark, indent=2, default=str)}\n```\n"
    )


def main() -> int:
    args = parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    real = load_real_data(args.ticker, args.start, args.end)
    synthetic_paths = generate_synthetic_paths(args.checkpoint, args.num_paths, len(real))

    stylized = stylized_facts_report(real, synthetic_paths)
    render_results_markdown(stylized, out_dir / "RESULTS.md")

    if args.benchmark:
        benchmark = run_strategy_benchmark(real, synthetic_paths)
        render_benchmark_markdown(benchmark, out_dir / "BENCHMARK_RESULTS.md")

    print(f"Wrote results to {out_dir}/RESULTS.md" + (" and BENCHMARK_RESULTS.md" if args.benchmark else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
